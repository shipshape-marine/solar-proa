"""
OpenFOAM case generation for the sail polar sweep.

Targets OpenFOAM v2412 from openfoam.com (ESI) - dictionary names differ in
the openfoam.org releases (e.g. momentumTransport vs turbulenceProperties).

Layout written under the run directory:

    sweep.json                 what was generated - read by postprocess.py
    Allrun                     meshes every reef level, then runs every case
    reef_<RR>/mesh/            blockMesh + snappyHexMesh, run once per reef
    reef_<RR>/aoa_<AA>/        simpleFoam at one angle of attack, reusing
                               the reef level's mesh

The domain is a box with a 'farfield' patch on all four sides
(freestreamVelocity/freestreamPressure), so the wind direction is set by the
initial/freestream velocity alone and one mesh serves every angle of attack.
Ground (sea surface) and top are slip walls: uniform wind, no atmospheric
gradient - the same assumption as ISO 12215-10's single wind speed. The sail
is a zero-thickness baffle; RANS k-omega SST with wall functions.
"""

import json
import math
import os
from typing import Any, Dict, List, Optional

from .geometry import sail_surface, write_ascii_stl

AIR_DENSITY = 1.2         # kg/m3, ISO 12215-10 Table 5 Note 3
AIR_VISCOSITY = 1.5e-5    # m2/s, kinematic
REFERENCE_SPEED = 10.0    # m/s - coefficients are taken as Reynolds-independent

# Sail surface refinement level and iteration count per mesh preset. Base
# cell size is fixed (BASE_CELL_M), so level 7 gives 2/2^7 = 16 mm cells.
BASE_CELL_M = 2.0
MESH_PRESETS = {
    'coarse': {'sail_level': 6, 'end_time': 1500},
    'medium': {'sail_level': 7, 'end_time': 2500},
    'fine':   {'sail_level': 8, 'end_time': 3500},
}

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by src/sail_cfd - edit the generator, not this file
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


def _foam_file(path: str, cls: str, obj: str, body: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        f.write(HEADER.format(cls=cls, obj=obj))
        f.write(body)


def _script(path: str, body: str) -> None:
    with open(path, 'w', newline='\n') as f:
        f.write(body)
    os.chmod(path, 0o755)


def _vec(v: List[float]) -> str:
    return f"({v[0]:.6g} {v[1]:.6g} {v[2]:.6g})"


def flow_directions(alpha_deg: float) -> Dict[str, List[float]]:
    """
    Unit drag (along the wind) and lift (perpendicular, toward the sail's
    leeward/+x side) directions for wind at angle of attack alpha to the
    chord (y axis), coming from the -x side.
    """
    a = math.radians(alpha_deg)
    return {
        'drag_dir': [math.sin(a), math.cos(a), 0.0],
        'lift_dir': [math.cos(a), -math.sin(a), 0.0],
    }


def _domain(chord: float, top: float) -> Dict[str, Any]:
    half_width = math.ceil(8 * chord / BASE_CELL_M) * BASE_CELL_M
    height = math.ceil(max(5 * top, top + 6 * chord) / BASE_CELL_M) * BASE_CELL_M
    return {
        'min': [-half_width, -half_width, 0.0],
        'max': [half_width, half_width, height],
        'cells': [int(2 * half_width / BASE_CELL_M)] * 2 + [int(height / BASE_CELL_M)],
    }


def write_mesh_case(case_dir: str, surface: Dict[str, Any], sail_level: int,
                    n_procs: int) -> None:
    """blockMesh + snappyHexMesh case for one reef level."""
    chord = surface['chord_m']
    top = surface['bounds_m']['max'][2]
    dom = _domain(chord, top)
    lo, hi = dom['min'], dom['max']

    os.makedirs(os.path.join(case_dir, 'constant', 'triSurface'), exist_ok=True)
    write_ascii_stl(os.path.join(case_dir, 'constant', 'triSurface', 'sail.stl'),
                    'sail', surface['triangles'])

    verts = [(lo[0], lo[1], lo[2]), (hi[0], lo[1], lo[2]), (hi[0], hi[1], lo[2]), (lo[0], hi[1], lo[2]),
             (lo[0], lo[1], hi[2]), (hi[0], lo[1], hi[2]), (hi[0], hi[1], hi[2]), (lo[0], hi[1], hi[2])]
    _foam_file(os.path.join(case_dir, 'system', 'blockMeshDict'), 'dictionary', 'blockMeshDict', f"""
scale 1;

vertices
(
{chr(10).join('    ' + _vec(v) for v in verts)}
);

blocks
(
    hex (0 1 2 3 4 5 6 7) ({dom['cells'][0]} {dom['cells'][1]} {dom['cells'][2]}) simpleGrading (1 1 1)
);

boundary
(
    ground   {{ type patch; faces ((0 3 2 1)); }}
    top      {{ type patch; faces ((4 5 6 7)); }}
    farfield {{ type patch; faces ((0 1 5 4) (1 2 6 5) (3 7 6 2) (0 4 7 3)); }}
);
""")

    b = surface['bounds_m']
    pad = 0.3 * chord
    near_min = [b['min'][0] - pad, b['min'][1] - pad, max(0.0, b['min'][2] - pad)]
    near_max = [b['max'][0] + pad, b['max'][1] + pad, b['max'][2] + pad]
    wake_radius = 2.0 * chord
    # Any point in the fluid, clear of the sail and of cell faces
    inside = [0.37 * lo[0] + 0.011, 0.41 * lo[1] + 0.013, 0.53 * hi[2] + 0.017]

    _foam_file(os.path.join(case_dir, 'system', 'snappyHexMeshDict'), 'dictionary', 'snappyHexMeshDict', f"""
castellatedMesh true;
snap            true;
addLayers       false;   // wall functions on the sail - no prism layers

geometry
{{
    sail.stl {{ type triSurfaceMesh; name sail; }}
    nearSail {{ type searchableBox; min {_vec(near_min)}; max {_vec(near_max)}; }}
    wake
    {{
        type    searchableCylinder;
        point1  (0 0 0);
        point2  (0 0 {near_max[2] + chord:.6g});
        radius  {wake_radius:.6g};
    }}
}}

castellatedMeshControls
{{
    maxLocalCells       4000000;
    maxGlobalCells      40000000;
    minRefinementCells  10;
    maxLoadUnbalance    0.10;
    nCellsBetweenLevels 3;
    features            ();

    refinementSurfaces
    {{
        sail
        {{
            level       ({sail_level} {sail_level});
            faceZone    sail;
            faceType    baffle;     // zero-thickness sail -> patches sail + sail_slave
            patchInfo   {{ type wall; }}
        }}
    }}

    resolveFeatureAngle 30;

    refinementRegions
    {{
        nearSail {{ mode inside; levels ((1e15 {sail_level - 2})); }}
        wake     {{ mode inside; levels ((1e15 3)); }}
    }}

    locationInMesh {_vec(inside)};
    allowFreeStandingZoneFaces true;
}}

snapControls
{{
    nSmoothPatch    3;
    tolerance       2.0;
    nSolveIter      50;
    nRelaxIter      5;
    nFeatureSnapIter 10;
    implicitFeatureSnap true;
    explicitFeatureSnap false;
    multiRegionFeatureSnap false;
}}

addLayersControls
{{
    relativeSizes true;
    layers {{}}
    expansionRatio 1.0;
    finalLayerThickness 0.3;
    minThickness 0.1;
    nGrow 0;
    featureAngle 60;
    nRelaxIter 3;
    nSmoothSurfaceNormals 1;
    nSmoothNormals 3;
    nSmoothThickness 10;
    maxFaceThicknessRatio 0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle 90;
    nBufferCellsNoExtrude 0;
    nLayerIter 50;
}}

meshQualityControls
{{
    maxNonOrtho 65;
    maxBoundarySkewness 20;
    maxInternalSkewness 4;
    maxConcave 80;
    minVol 1e-13;
    minTetQuality 1e-15;
    minArea -1;
    minTwist 0.02;
    minDeterminant 0.001;
    minFaceWeight 0.05;
    minVolRatio 0.01;
    minTriangleTwist -1;
    nSmoothScale 4;
    errorReduction 0.75;
    relaxed {{ maxNonOrtho 75; }}
}}

mergeTolerance 1e-6;
""")

    _write_common_system(case_dir, n_procs, end_time=1)
    _script(os.path.join(case_dir, 'Allrun'), """#!/bin/sh
cd "${0%/*}" || exit
. ${WM_PROJECT_DIR:?}/bin/tools/RunFunctions

runApplication blockMesh
runApplication decomposePar -force
runParallel snappyHexMesh -overwrite
runApplication reconstructParMesh -constant
runApplication checkMesh -constant
""")


def _write_common_system(case_dir: str, n_procs: int, end_time: int,
                         functions: str = '') -> None:
    _foam_file(os.path.join(case_dir, 'system', 'controlDict'), 'dictionary', 'controlDict', f"""
application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {end_time};
deltaT          1;
writeControl    timeStep;
writeInterval   {max(1, end_time // 2)};
purgeWrite      1;
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{
{functions}
}}
""")
    _foam_file(os.path.join(case_dir, 'system', 'decomposeParDict'), 'dictionary', 'decomposeParDict', f"""
numberOfSubdomains {n_procs};
method          scotch;
""")
    _foam_file(os.path.join(case_dir, 'system', 'fvSchemes'), 'dictionary', 'fvSchemes', """
ddtSchemes      { default steadyState; }
gradSchemes     { default Gauss linear; grad(U) cellLimited Gauss linear 1; }
divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwindV grad(U);
    div(phi,k)      bounded Gauss upwind;
    div(phi,omega)  bounded Gauss upwind;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear limited corrected 0.33; }
interpolationSchemes { default linear; }
snGradSchemes   { default limited corrected 0.33; }
wallDist        { method meshWave; }
""")
    _foam_file(os.path.join(case_dir, 'system', 'fvSolution'), 'dictionary', 'fvSolution', """
solvers
{
    p
    {
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-7;
        relTol          0.1;
    }
    "(U|k|omega)"
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0.1;
    }
}

SIMPLE
{
    nNonOrthogonalCorrectors 0;
    consistent      yes;
    residualControl { p 1e-4; U 1e-5; "(k|omega)" 1e-5; }
}

// Conservative for the stalled, unsteady high-alpha cases
relaxationFactors { equations { U 0.7; ".*" 0.7; } }
""")


def write_aoa_case(case_dir: str, alpha_deg: float, n_procs: int, end_time: int) -> None:
    """simpleFoam case for one angle of attack; mesh is copied in by Allrun."""
    dirs = flow_directions(alpha_deg)
    u = [REFERENCE_SPEED * c for c in dirs['drag_dir']]
    k = 1.5 * (0.01 * REFERENCE_SPEED)**2       # 1% turbulence intensity
    omega = k / (10 * AIR_VISCOSITY)             # eddy viscosity ratio 10

    forces = f"""    forces
    {{
        type            forces;
        libs            (forces);
        writeControl    timeStep;
        writeInterval   1;
        patches         ("sail.*");
        rho             rhoInf;
        rhoInf          {AIR_DENSITY};
        CofR            (0 0 0);    // sea surface below the pivot - see postprocess.py
        log             false;
    }}"""
    _write_common_system(case_dir, n_procs, end_time, functions=forces)

    _foam_file(os.path.join(case_dir, 'constant', 'transportProperties'), 'dictionary',
               'transportProperties', f"""
transportModel  Newtonian;
nu              {AIR_VISCOSITY};
""")
    _foam_file(os.path.join(case_dir, 'constant', 'turbulenceProperties'), 'dictionary',
               'turbulenceProperties', """
simulationType  RAS;
RAS
{
    RASModel        kOmegaSST;
    turbulence      on;
    printCoeffs     on;
}
""")

    _foam_file(os.path.join(case_dir, '0', 'U'), 'volVectorField', 'U', f"""
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform {_vec(u)};
boundaryField
{{
    farfield    {{ type freestreamVelocity; freestreamValue uniform {_vec(u)}; }}
    ground      {{ type slip; }}
    top         {{ type slip; }}
    "sail.*"    {{ type noSlip; }}
}}
""")
    _foam_file(os.path.join(case_dir, '0', 'p'), 'volScalarField', 'p', """
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0;
boundaryField
{
    farfield    { type freestreamPressure; freestreamValue uniform 0; }
    ground      { type zeroGradient; }
    top         { type zeroGradient; }
    "sail.*"    { type zeroGradient; }
}
""")
    for name, value, wall in (('k', k, 'kqRWallFunction'), ('omega', omega, 'omegaWallFunction')):
        dims = '[0 2 -2 0 0 0 0]' if name == 'k' else '[0 0 -1 0 0 0 0]'
        _foam_file(os.path.join(case_dir, '0', name), 'volScalarField', name, f"""
dimensions      {dims};
internalField   uniform {value:.6g};
boundaryField
{{
    farfield    {{ type inletOutlet; inletValue uniform {value:.6g}; value uniform {value:.6g}; }}
    ground      {{ type zeroGradient; }}
    top         {{ type zeroGradient; }}
    "sail.*"    {{ type {wall}; value uniform {value:.6g}; }}
}}
""")
    _foam_file(os.path.join(case_dir, '0', 'nut'), 'volScalarField', 'nut', """
dimensions      [0 2 -1 0 0 0 0];
internalField   uniform 0;
boundaryField
{
    farfield    { type calculated; value uniform 0; }
    ground      { type calculated; value uniform 0; }
    top         { type calculated; value uniform 0; }
    "sail.*"    { type nutkWallFunction; value uniform 0; }
}
""")

    _script(os.path.join(case_dir, 'Allrun'), """#!/bin/sh
cd "${0%/*}" || exit
. ${WM_PROJECT_DIR:?}/bin/tools/RunFunctions

rm -rf constant/polyMesh
cp -r ../mesh/constant/polyMesh constant/
runApplication decomposePar -force
runParallel simpleFoam
""")


def generate_sweep(run_dir: str, params: Dict[str, Any], parameters_path: str,
                   reef_levels: List[float], alphas: List[float],
                   sail_camber_mm: float, sail_angle_deg: float,
                   mesh: str, n_procs: int, full_polar: bool = True,
                   chord_camber_pct: Optional[float] = None) -> Dict[str, Any]:
    """
    Write every mesh and angle-of-attack case plus sweep.json and a top-level Allrun.
    full_polar=False drops the 0-90 deg span check, for studies (trim.py)
    whose results don't become a sail_aero polar. chord_camber_pct swaps the
    CAD sail shape for a chordwise-cambered one (geometry.sail_surface).
    """
    if mesh not in MESH_PRESETS:
        raise ValueError(f"mesh must be one of {list(MESH_PRESETS)}, got {mesh!r}")
    if full_polar and (min(alphas) > 0 or max(alphas) < 90):
        raise ValueError("alphas must span 0-90 deg - sail_aero requires the full range")
    if min(alphas) < 0 or max(alphas) > 90:
        raise ValueError(f"alphas must lie within 0-90 deg, got {sorted(alphas)}")
    preset = MESH_PRESETS[mesh]

    if os.path.exists(run_dir) and os.listdir(run_dir):
        raise FileExistsError(f"{run_dir} already exists and is not empty - pick a new run "
                              "directory so earlier results aren't overwritten")
    os.makedirs(run_dir, exist_ok=True)

    sweep = {
        'parameters': parameters_path,
        'sail_camber_mm': sail_camber_mm,
        'sail_angle_deg': sail_angle_deg,
        'chord_camber_pct': chord_camber_pct,
        'mesh': mesh,
        'sail_level': preset['sail_level'],
        'base_cell_m': BASE_CELL_M,
        'end_time': preset['end_time'],
        'reference_speed_ms': REFERENCE_SPEED,
        'air_density': AIR_DENSITY,
        'reefs': [],
    }

    run_lines = ['#!/bin/sh', 'cd "${0%/*}" || exit', 'set -e', '']
    for reef in sorted(reef_levels):
        surface = sail_surface(params, reef, sail_camber_mm, sail_angle_deg,
                               chord_camber_pct=chord_camber_pct)
        reef_dir = f"reef_{reef:02.0f}"
        write_mesh_case(os.path.join(run_dir, reef_dir, 'mesh'), surface,
                        preset['sail_level'], n_procs)
        # Invoked via sh: execute bits don't survive writing from Windows
        run_lines.append(f'echo "== {reef_dir}: mesh"; sh ./{reef_dir}/mesh/Allrun')

        cases = []
        for alpha in sorted(alphas):
            # aoa_20, or aoa_12p5 for half degrees
            case_name = (f"aoa_{alpha:02.0f}" if float(alpha).is_integer()
                         else f"aoa_{alpha:04.1f}".replace('.', 'p'))
            write_aoa_case(os.path.join(run_dir, reef_dir, case_name), alpha, n_procs,
                           preset['end_time'])
            run_lines.append(f'echo "== {reef_dir}/{case_name}"; sh ./{reef_dir}/{case_name}/Allrun')
            cases.append({'angle_of_attack_deg': alpha, 'case': f"{reef_dir}/{case_name}",
                          **flow_directions(alpha)})

        sweep['reefs'].append({
            'reefing_percentage': reef,
            'reference_area_m2': surface['reference_area_m2'],
            'geometric_ce_height_m': surface['geometric_ce_height_m'],
            'chord_m': surface['chord_m'],
            'cases': cases,
        })

    _script(os.path.join(run_dir, 'Allrun'), '\n'.join(run_lines) + '\n')
    with open(os.path.join(run_dir, 'sweep.json'), 'w') as f:
        json.dump(sweep, f, indent=2)
    return sweep
